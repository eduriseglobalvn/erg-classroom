export const useLang = create<{ lang: "vi" | "en"; toggle: () => void }>((set, get) => ({
  // English unless the teacher switched to Vietnamese
  lang: (() => { try { return localStorage.getItem("lang") === "vi" ? "vi" : "en"; } catch { return "en"; } })(),
  toggle: () => {
    const lang = get().lang === "vi" ? "en" : "vi";
    try { localStorage.setItem("lang", lang); } catch { /* private mode: not remembered */ }
    set({ lang });
  },
}));

export const tr = (lang: "vi" | "en", vi: string) => (lang === "en" ? EN[vi] ?? vi : vi);
